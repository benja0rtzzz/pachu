const DITHER_SPREAD = 1.1;

type Props = {
  color?: string;
  style?: StyleProp<ViewStyle>;
};

function dotOpacity(radius: number) {
  return Math.min(0.94, 0.58 + radius / 32);
}

export function DoveCornerMark({ color = colors.accent, style }: Props) {
  return (
    <Svg
      height="100%"
      pointerEvents="none"
      preserveAspectRatio="xMaxYMin meet"
      style={[styles.svg, style]}
      viewBox="512 146 512 760"
      width="100%"
    >
      <G transform="translate(1536 0) scale(-1 1)">
        {DOVE_DOTS.map(([cx, cy, r], index) => (
          <Circle
            key={`${cx}-${cy}-${index}`}
            cx={cx}
            cy={cy}
            fill={color}
            opacity={dotOpacity(r * DITHER_SPREAD)}
            r={r * DITHER_SPREAD}
          />
        ))}
      </G>
    </Svg>
  );
}

const styles = StyleSheet.create({
  svg: {
    ...StyleSheet.absoluteFillObject,
  },
});
